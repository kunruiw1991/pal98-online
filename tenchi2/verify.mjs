import vm from 'node:vm';
import fs from 'node:fs';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
const sandbox={module:{exports:{}},exports:{}};
sandbox.exports=sandbox.module.exports;
vm.runInNewContext(fs.readFileSync(new URL('./jsnes.min.js',import.meta.url),'utf8'),sandbox);
const {NES,Controller}=sandbox.module.exports;
const rom=fs.readFileSync(new URL('./doae2j.nes',import.meta.url));
assert.equal(crypto.createHash('sha256').update(rom).digest('hex'),'2bc5970f8e2b6ddd0172e900b78d5234ed1919954cf00434a86ca18166a6f4bf');
let frame,frames=0,samples=0;
const nes=new NES({onFrame:b=>{frame=Array.from(b);frames++;},onAudioSample:()=>samples++});
nes.loadROM(rom);
assert.equal(nes.rom.mapperType,4);
for(let i=0;i<600;i++)nes.frame();
assert.equal(frames,600);assert(samples>100000);assert(new Set(frame).size>5);
fs.writeFileSync(new URL('./title-frame.rgba',import.meta.url),Buffer.from(frame.flatMap(v=>[v&255,(v>>8)&255,(v>>16)&255,255])));
const title=crypto.createHash('sha256').update(Buffer.from(frame.flatMap(v=>[v&255,(v>>8)&255,(v>>16)&255]))).digest('hex');
nes.buttonDown(1,Controller.BUTTON_START);for(let i=0;i<3;i++)nes.frame();nes.buttonUp(1,Controller.BUTTON_START);for(let i=0;i<180;i++)nes.frame();
const state=JSON.parse(JSON.stringify(nes.toJSON()));assert(Array.isArray(state.cpu.mem));assert.equal(state.cpu.mem.length,65536);
for(let i=0;i<60;i++)nes.frame();const expected=JSON.stringify(nes.toJSON());
const other=new NES();other.loadROM(rom);other.fromJSON(state);for(let i=0;i<60;i++)other.frame();
assert.equal(JSON.stringify(other.toJSON()),expected,'Save restore must resume identical emulation state');
console.log(JSON.stringify({romSha256:crypto.createHash('sha256').update(rom).digest('hex'),mapper:4,frames:843,audioSamples:samples,titleFrameSha256:title,saveStateBytes:Buffer.byteLength(JSON.stringify(state)),saveRestore:'identical after 60 frames',result:'PASS'},null,2));
